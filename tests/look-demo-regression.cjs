const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const js = fs.readFileSync(path.join(root, 'assets/studio-look-demo.js'), 'utf8');
function control(extra={}) { return {attrs:{},listeners:{},setAttribute(k,v){this.attrs[k]=v},addEventListener(k,v){this.listeners[k]=v},removeEventListener(k,v){if(this.listeners[k]===v)delete this.listeners[k]},...extra}; }
const frame=control({style:{values:{},setProperty(k,v){this.values[k]=v}},getBoundingClientRect:()=>({left:10,width:200}),setPointerCapture(id){this.capture=id},hasPointerCapture(id){return this.capture===id},releasePointerCapture(){this.capture=null}});
const range=control({value:'50'}),output={},caption={};
const buttons=['warm','cool','mono','unexpected'].map(look=>control({dataset:{lookChoice:look}}));
const fields=[{disabled:true},{disabled:true}];
const study={dataset:{look:'warm'},querySelector:s=>({'.look-frame':frame,'#look-compare':range,'#look-coverage':output,'#look-after-label':caption}[s]),querySelectorAll:s=>s==='[data-look-choice]'?buttons:fields};
vm.runInNewContext(js,{document:{querySelector:()=>study}});
assert(fields.every(f=>f.disabled===false),'Only initialized controls become interactive');
assert.equal(frame.style.values['--nv-compare'],'50%');
assert.equal(output.textContent,'50% original');
buttons[1].listeners.click();
assert.equal(study.dataset.look,'cool');assert.equal(caption.textContent,'Cool dusk');
assert.equal(buttons[1].attrs['aria-pressed'],'true');assert.equal(buttons[0].attrs['aria-pressed'],'false');
range.value='0';range.listeners.input();assert.equal(frame.style.values['--nv-compare'],'0%');
assert.equal(range.attrs['aria-valuetext'],'0% original, 100% Cool dusk');
range.value='100';range.listeners.input();assert.equal(output.textContent,'100% original');
range.value='120';range.listeners.input();assert.equal(frame.style.values['--nv-compare'],'100%');
buttons[3].listeners.click();assert.equal(study.dataset.look,'cool','Reject unknown looks');
frame.listeners.pointerdown({button:0,isPrimary:true,pointerId:1,clientX:110});
assert.equal(range.value,'50','Direct image press moves comparison');
frame.listeners.pointermove({pointerId:1,clientX:160});assert.equal(range.value,'75');
frame.listeners.pointermove({pointerId:2,clientX:210});assert.equal(range.value,'75','Ignore other fingers');
frame.listeners.pointerup({type:'pointerup',pointerId:1,clientX:210});assert.equal(range.value,'100');
assert.equal(frame.capture,null);assert(!frame.listeners.pointermove,'No continuous pointer listener after release');
frame.listeners.pointerdown({button:0,pointerId:3,clientX:10});frame.listeners.pointercancel({type:'pointercancel',pointerId:3});
assert(!frame.listeners.pointermove,'Cancelled drags clean up');
vm.runInNewContext(js,{document:{querySelector:()=>null}});
vm.runInNewContext(js,{document:{querySelector:()=>({...study,querySelector:()=>null})}});
assert(!/fetch\(|localStorage|sessionStorage|innerHTML|preventDefault/.test(js),'Illustration must not access accounts/network or intercept navigation');
const html=fs.readFileSync(path.join(root,'video-editor/index.html'),'utf8');
assert(html.includes('Interactive website illustration using image filters, not a native app render.'),'Do not misrepresent browser filters as app output');
assert(html.includes('<noscript>'),'Readable no-JS fallback');
assert(html.includes('type="range"'),'Native keyboard/touch accessible comparison slider');
assert(html.includes('aria-label="Drag to compare original image coverage"'),'Accessible name contains the visible label for voice control');
